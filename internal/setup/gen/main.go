// Command gen writes assocs_gen.go from wails.json's file associations.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"
)

func main() {
	data, err := os.ReadFile("../../wails.json")
	if err != nil {
		panic(err)
	}
	var w struct {
		Info struct {
			FileAssociations []struct{ Ext, Name, Description string } `json:"fileAssociations"`
		} `json:"info"`
	}
	if err := json.Unmarshal(data, &w); err != nil {
		panic(err)
	}
	var b strings.Builder
	b.WriteString("// Code generated by go generate (gen/main.go) from wails.json; DO NOT EDIT.\n\npackage setup\n\nvar assocs = []Assoc{\n")
	for _, a := range w.Info.FileAssociations {
		fmt.Fprintf(&b, "\t{Ext: %q, ProgID: %q, Description: %q},\n", a.Ext, a.Name, a.Description)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("assocs_gen.go", []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}
